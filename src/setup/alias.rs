//! Aliases for either front end — `cm --install-alias wsl`,
//! `container-distro install-alias cd` — plus a `<name>.1` man-page
//! link so `man wsl` works too.
//!
//! An alias is a generated `/bin/sh` script, not a symlink, because it
//! has to record *which* front end it runs: `exec '<binary>'
//! --invoked-as "$0" [cli] "$@"`. The binary is this one,
//! canonicalized. `--invoked-as` tells the alias's process where the
//! alias lives, so a bare-name alias created *through* it lands beside
//! it rather than beside the resolved binary.
//!
//! Removal is strictly verified: only a script carrying our marker
//! line, or a legacy symlink resolving to this binary, is deleted;
//! anything else is refused or left alone.

use std::env;
use std::fs;
use std::io::ErrorKind;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

use crate::distro::write_nofollow;
use crate::setup::layout::{self, FrontEnd, INVOKED_AS_FLAG};
use crate::setup::{man, plugin};

/// The second line of every generated alias — what `uninstall-alias`
/// and a re-run of `install-alias` recognize.
const MARKER: &str = "# container-distro alias — generated by install-alias; edits are overwritten";

/// The man page an alias of `fe` links to.
fn man_page(fe: FrontEnd) -> &'static str {
    match fe {
        FrontEnd::Cm => "cm.1",
        FrontEnd::Distro => "container-distro.1",
    }
}

/// `'…'` for `/bin/sh`.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// The alias script running `exe` with `prefix` leading arguments.
fn script(exe: &Path, prefix: &[&str]) -> Result<String> {
    let exe = exe.to_str().context("the binary's path is not UTF-8")?;
    if exe.contains('\n') {
        bail!("the binary's path contains a newline");
    }
    let mut line = format!("exec {} {INVOKED_AS_FLAG} \"$0\"", sh_quote(exe));
    for a in prefix {
        line.push(' ');
        line.push_str(a);
    }
    Ok(format!("#!/bin/sh\n{MARKER}\n{line} \"$@\"\n"))
}

fn is_our_script(contents: &str) -> bool {
    contents.starts_with(&format!("#!/bin/sh\n{MARKER}\n"))
}

/// Resolve `NAME` or `PATH` into the alias's absolute path. A path is
/// used as given (relative to the cwd). A bare name goes beside the
/// alias this process was started through, else beside the running
/// binary — except the plugin copy, whose directory is `container`'s
/// (usually root-owned) plugin tree.
fn alias_path(target: &str) -> Result<PathBuf> {
    alias_path_in(target, layout::invoked_as(), &layout::current_exe()?)
}

fn alias_path_in(target: &str, invoked_as: Option<&Path>, exe: &Path) -> Result<PathBuf> {
    if target.is_empty() {
        bail!("empty alias");
    }
    let path = PathBuf::from(target);
    if path.is_absolute() {
        return Ok(path);
    }
    if target.contains('/') {
        // `./foo` reads better without the `.` once absolute.
        let rel: PathBuf = path
            .components()
            .filter(|c| !matches!(c, std::path::Component::CurDir))
            .collect();
        return Ok(env::current_dir()?.join(rel));
    }
    let base = match invoked_as {
        Some(alias) => alias,
        None if exe.file_name().is_some_and(|n| n == plugin::PLUGIN_NAME) => bail!(
            "this is the `container distro` plugin copy — pass an alias PATH, \
             or run install-alias from `container-distro` or `cm`"
        ),
        None => exe,
    };
    let dir = base
        .parent()
        .context("no directory to place the alias in")?;
    Ok(dir.join(target))
}

fn alias_name(link: &Path) -> Result<String> {
    link.file_name()
        .and_then(|n| n.to_str())
        .map(str::to_string)
        .with_context(|| format!("{} is not a usable file name", link.display()))
}

/// Where the symlink's target actually points (relative links resolved
/// against the link's directory), whether or not it still exists.
fn link_target(link: &Path) -> Result<PathBuf> {
    let t = fs::read_link(link).with_context(|| format!("failed to read {}", link.display()))?;
    if t.is_absolute() {
        Ok(t)
    } else {
        Ok(link
            .parent()
            .map(|p| p.join(&t))
            .unwrap_or_else(|| t.clone()))
    }
}

fn points_to(link: &Path, target: &Path) -> bool {
    link_target(link)
        .map(|t| t.canonicalize().unwrap_or(t) == *target)
        .unwrap_or(false)
}

/// `alias.1` -> `page` in the man dir of this install (already on the
/// manpath, wherever the alias itself lives). Only links when `page` is
/// installed — installing the alias doesn't install man pages, and a
/// later `install-man` + `install-alias` adds just the link.
fn install_man_link(name: &str, page: &str) -> Result<()> {
    let dir = match man::default_man_dir() {
        Ok(d) => d,
        // e.g. a dev build with no install prefix — the alias still
        // stands; just skip the man link.
        Err(e) => {
            eprintln!("note: skipping {name}.1 ({e:#})");
            return Ok(());
        }
    };
    let target = dir.join(page);
    if !target.is_file() {
        eprintln!(
            "note: {page} isn't installed in {}; skipping {name}.1 (install the man pages first)",
            dir.display()
        );
        return Ok(());
    }
    let link = dir.join(format!("{name}.1"));
    match link.symlink_metadata() {
        Ok(m) if m.file_type().is_symlink() => {
            if points_to(&link, &target) {
                println!("{} already points to {page}", link.display());
            } else {
                eprintln!(
                    "not touching {}: a symlink, but not to {page}",
                    link.display()
                );
            }
        }
        Ok(_) => eprintln!("not touching {}: not a symlink", link.display()),
        Err(e) if e.kind() == ErrorKind::NotFound => {
            // Relative link: the page must resolve in this directory.
            symlink(page, &link).with_context(|| format!("failed to create {}", link.display()))?;
            println!("Installed {} -> {page}", link.display());
        }
        Err(e) => return Err(e).with_context(|| format!("failed to stat {}", link.display())),
    }
    Ok(())
}

/// `install-alias NAME|PATH` — an alias script running front end `fe`
/// of this binary, plus a `<name>(1)` man-page link. Re-running updates
/// one of ours in place; a legacy symlink alias pointing at this binary
/// is upgraded to a script; anything else at the path is refused.
pub fn install(target: &str, fe: FrontEnd) -> Result<()> {
    let link = alias_path(target)?;
    let (exe, prefix) = layout::self_invocation(fe)?;
    if link == exe {
        bail!("`{target}` resolves to the binary itself");
    }
    let body = script(&exe, prefix)?;
    if let Some(dir) = link.parent() {
        fs::create_dir_all(dir).with_context(|| format!("failed to create {}", dir.display()))?;
    }
    match link.symlink_metadata() {
        Ok(m) if m.file_type().is_symlink() => {
            if !points_to(&link, &exe) {
                bail!(
                    "{} is a symlink to something else — refusing to replace it",
                    link.display()
                );
            }
            // write_nofollow swaps the link for the script.
            write_nofollow(&link, body.as_bytes(), 0o755)?;
            println!("Upgraded {} to an alias script", link.display());
        }
        Ok(_) => {
            let current = fs::read_to_string(&link).unwrap_or_default();
            if !is_our_script(&current) {
                bail!(
                    "{} exists and isn't one of our aliases — refusing",
                    link.display()
                );
            }
            if current == body {
                println!("{} is already up to date", link.display());
            } else {
                write_nofollow(&link, body.as_bytes(), 0o755)?;
                println!("Updated {}", link.display());
            }
        }
        Err(e) if e.kind() == ErrorKind::NotFound => {
            write_nofollow(&link, body.as_bytes(), 0o755)?;
            println!("Installed {} -> {}", link.display(), exe.display());
        }
        Err(e) => return Err(e).with_context(|| format!("failed to stat {}", link.display())),
    }
    install_man_link(&alias_name(&link)?, man_page(fe))
}

/// `uninstall-alias NAME|PATH` — remove the alias and its man-page
/// link, only when each is provably ours.
pub fn uninstall(target: &str) -> Result<()> {
    let link = alias_path(target)?;
    let exe = layout::current_exe()?;
    match link.symlink_metadata() {
        Ok(m) if m.file_type().is_symlink() => {
            if !points_to(&link, &exe) {
                bail!(
                    "{} is a symlink, but not to this binary — refusing",
                    link.display()
                );
            }
            remove(&link)?;
        }
        Ok(_) => {
            if !is_our_script(&fs::read_to_string(&link).unwrap_or_default()) {
                bail!("{} isn't one of our aliases — refusing", link.display());
            }
            remove(&link)?;
        }
        Err(e) if e.kind() == ErrorKind::NotFound => {
            println!("Not installed ({})", link.display());
        }
        Err(e) => return Err(e).with_context(|| format!("failed to stat {}", link.display())),
    }
    // The man-page link: only remove a symlink to one of our pages.
    let Ok(man_dir) = man::default_man_dir() else {
        return Ok(());
    };
    let man_link = man_dir.join(format!("{}.1", alias_name(&link)?));
    match man_link.symlink_metadata() {
        Ok(m) if m.file_type().is_symlink() => {
            let ours = [FrontEnd::Cm, FrontEnd::Distro]
                .iter()
                .any(|&fe| points_to(&man_link, &man_dir.join(man_page(fe))));
            if ours {
                remove(&man_link)?;
            } else {
                eprintln!(
                    "not removing {}: a symlink, but not to one of our pages",
                    man_link.display()
                );
            }
        }
        Ok(_) => eprintln!("not removing {}: not a symlink", man_link.display()),
        Err(_) => {} // missing man page or dir — nothing to do
    }
    Ok(())
}

fn remove(path: &Path) -> Result<()> {
    fs::remove_file(path).with_context(|| format!("failed to remove {}", path.display()))?;
    println!("Removed {}", path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn relative_path_resolves_against_cwd() {
        let p = alias_path_in("sub/wsl", None, Path::new("/x/bin/cm")).unwrap();
        assert_eq!(p, env::current_dir().unwrap().join("sub/wsl"));
    }

    #[test]
    fn bare_name_lands_next_to_exe() {
        let p = alias_path_in("wsl", None, Path::new("/x/bin/cm")).unwrap();
        assert_eq!(p, Path::new("/x/bin/wsl"));
    }

    #[test]
    fn bare_name_follows_the_invoking_alias() {
        let p = alias_path_in(
            "wsl",
            Some(Path::new("/a/bin/test-cd")),
            Path::new("/w/target/debug/container-distro"),
        )
        .unwrap();
        assert_eq!(p, Path::new("/a/bin/wsl"));
    }

    #[test]
    fn plugin_copy_needs_an_explicit_path() {
        let exe = Path::new("/c/libexec/container-plugins/distro/bin/distro");
        assert!(alias_path_in("wsl", None, exe).is_err());
        assert!(alias_path_in("/u/bin/wsl", None, exe).is_ok());
    }

    #[test]
    fn script_records_front_end_and_invocation() {
        let s = script(Path::new("/opt/it's/container-distro"), &["cli"]).unwrap();
        assert!(is_our_script(&s));
        assert_eq!(
            s.lines().nth(2).unwrap(),
            r#"exec '/opt/it'\''s/container-distro' --invoked-as "$0" cli "$@""#
        );
        assert!(script(Path::new("/a\nb"), &[]).is_err());
    }

    #[test]
    fn script_runs_the_requested_front_end() {
        // A real /bin/sh run of a generated alias against a stub
        // binary that echoes its argv.
        let d = tempfile::tempdir().unwrap();
        let stub = d.path().join("stub");
        fs::write(&stub, "#!/bin/sh\nprintf '%s\\n' \"$@\"\n").unwrap();
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&stub, fs::Permissions::from_mode(0o755)).unwrap();
        let alias = d.path().join("wsl");
        write_nofollow(&alias, script(&stub, &["cli"]).unwrap().as_bytes(), 0o755).unwrap();
        let out = std::process::Command::new(&alias)
            .args(["-d", "a b"])
            .output()
            .unwrap();
        let alias = alias.display().to_string();
        assert_eq!(
            String::from_utf8(out.stdout)
                .unwrap()
                .lines()
                .collect::<Vec<_>>(),
            ["--invoked-as", alias.as_str(), "cli", "-d", "a b"]
        );
    }

    #[test]
    fn foreign_files_are_not_ours() {
        assert!(!is_our_script("#!/bin/sh\nexec /usr/bin/true\n"));
        let tmp = tempfile::tempdir().unwrap();
        let decoy = tmp.path().join("other-binary");
        fs::write(&decoy, b"").unwrap();
        let link = tmp.path().join("wsl");
        symlink(&decoy, &link).unwrap();
        assert!(!points_to(&link, &layout::current_exe().unwrap()));
    }
}
